function abrirRegalo(tipo) {

    const regalo = event.currentTarget;
    const tapa = regalo.querySelector(".tapa");
    const sobre = regalo.querySelector(".sobre");

    tapa.style.transform = "rotateX(180deg)";
    sobre.style.transform = "scale(1.08)";


    setTimeout(() => {

        document.getElementById("mensaje").innerHTML =
            mensajes[tipo];

        document
            .getElementById("modal")
            .classList.add("activo");


        setTimeout(() => {
            tapa.style.transform = "";
            sobre.style.transform = "";
        }, 400);

    }, 550);

}


function cerrarRegalo() {

    document
        .getElementById("modal")
        .classList.remove("activo");
}

document.getElementById("modal").addEventListener("click", function(event) {

    if (event.target === this) {
        cerrarRegalo();
    }

});
